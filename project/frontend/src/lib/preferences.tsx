type PreferencesValue = {
  language: Language;
  theme: Theme;
  setLanguage: (language: Language) => void;
  setTheme: (theme: Theme) => void;
  t: (text: string, values?: Record<string, string | number | null | undefined>) => string;
};

const PreferencesContext = createContext<PreferencesValue | null>(null);

function savedChoice<T extends string>(key: string, fallback: T, allowed: readonly T[]): T {
  try {
    const value = window.localStorage.getItem(key);
    return allowed.includes(value as T) ? value as T : fallback;
  } catch {
    return fallback;
  }
}

export function PreferencesProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => savedChoice("movie-language", "vi", ["vi", "en"]));
  const [theme, setTheme] = useState<Theme>(() => savedChoice("movie-theme", "dark", ["dark", "light"]));
  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dataset.theme = theme;
    const themeColor = document.querySelector<HTMLMetaElement>('meta[name="theme-color"]');
    if (themeColor) themeColor.content = theme === "light" ? "#f4f6f8" : "#05090b";
    const description = document.querySelector<HTMLMetaElement>('meta[name="description"]');
    if (description) description.content = language === "en"
      ? "MOVIE — Explore films and find your next favorite with machine learning."
      : "MOVIE — Khám phá thế giới phim ảnh và tìm bộ phim dành cho bạn với công nghệ học máy.";
    try {
      window.localStorage.setItem("movie-language", language);
      window.localStorage.setItem("movie-theme", theme);
    } catch {
      // Preferences still work for the current session when storage is unavailable.
    }
  }, [language, theme]);
  const value = useMemo<PreferencesValue>(() => ({
    language,
    theme,
    setLanguage,
    setTheme,
    t: (text, values) => {
      const translated = language === "en" ? translations[text] ?? text : text;
      return values ? translated.replace(/\{(\w+)\}/g, (_match, key: string) => values[key] == null ? "—" : String(values[key])) : translated;
    },
  }), [language, theme]);
  return <PreferencesContext.Provider value={value}>{children}</PreferencesContext.Provider>;
}

export function usePreferences() {
  const value = useContext(PreferencesContext);
  if (!value) throw new Error("usePreferences must be used inside PreferencesProvider");
  return value;
}
